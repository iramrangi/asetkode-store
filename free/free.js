  document.getElementById('catTabs').addEventListener('click', (e) => {
    const cat = e.target.getAttribute('data-cat');
    if (!cat) return;
    activeCat = cat;
    document.querySelectorAll('.free-tab').forEach((b) => b.classList.toggle('active', b.getAttribute('data-cat') === cat));
    render();
  });
  document.getElementById('freeSearch').addEventListener('input', (e) => {
    searchQ = e.target.value;
    render();
  });
  document.getElementById('free-catalog').addEventListener('click', (e) => {
    if (!e.target.closest('[data-free-reset]')) return;
    searchQ = '';
    activeCat = 'all';
    document.getElementById('freeSearch').value = '';
    document.querySelectorAll('.free-tab').forEach((b) => b.classList.toggle('active', b.getAttribute('data-cat') === 'all'));
    render();
  });
  document.getElementById('langBtn').addEventListener('click', () => {
    isEn = !isEn;
    render();
  });
  const gfLink = document.getElementById('gfontLink');
  if (gfLink && gfLink.media !== 'all') gfLink.media = 'all';
  render();
